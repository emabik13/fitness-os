/* FITNESS OS service worker — offline support for the installed PWA.
 * %BASE_URL% and %BUILD_ID% are replaced by scripts/build-web.js. */
const BASE = '%BASE_URL%';
const CACHE = 'fitness-os-%BUILD_ID%';
const SHELL = [BASE + '/', BASE + '/manifest.json', BASE + '/apple-touch-icon.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('fitness-os-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // App navigations: network first (to get updates), cached shell when offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(BASE + '/', copy));
          return res;
        })
        .catch(() => caches.match(BASE + '/')),
    );
    return;
  }

  // Hashed bundles, fonts, images: cache first, then network (and store).
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
